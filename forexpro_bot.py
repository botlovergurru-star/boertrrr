async def broadcast(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    """Owner only: /broadcast Your message here"""
    if update.effective_user.id != OWNER_ID:
        return
    if not ctx.args:
        await update.message.reply_text("Usage: /broadcast Your message")
        return
    msg = " ".join(ctx.args)
    await update.message.reply_text(f"📢 Broadcast sent:\n\n{msg}", parse_mode="Markdown")

async def send_signal(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    """Owner only: /signal — sends sample signal"""
    if update.effective_user.id != OWNER_ID:
        return
    await update.message.reply_text(SIGNAL_EXAMPLE, parse_mode="Markdown")

