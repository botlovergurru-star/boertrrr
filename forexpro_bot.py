    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("services", lambda u, c: u.message.reply_text(SERVICES, parse_mode="Markdown", reply_markup=services_inline())))
    app.add_handler(CommandHandler("pay", lambda u, c: u.message.reply_text(PAYMENT_MSG, parse_mode="Markdown", reply_markup=pay_inline())))
    app.add_handler(CommandHandler("signal", send_signal))
    app.add_handler(CommandHandler("broadcast", broadcast))
